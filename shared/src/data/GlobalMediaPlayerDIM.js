/**
 * 🛠️ HELPER: Bezpečný vyťahovač stôp pre 16 Dimenzií
 * Podporuje vstupy: "ID-00", "ID00", "00", "id00"
 */
export const getDimensionMediaData = (dimId) => {
  const clean = String(dimId || "ID-00").trim().toUpperCase();
  const normalizedKey = clean.startsWith("ID-")
    ? clean
    : clean.startsWith("ID")
    ? `ID-${clean.replace("ID", "")}`
    : `ID-${clean}`;

  if (GLOBAL_MEDIA_REGISTER_DIM[normalizedKey]) {
    return GLOBAL_MEDIA_REGISTER_DIM[normalizedKey];
  }

  return GLOBAL_MEDIA_REGISTER_DIM["ID-00"];
};

