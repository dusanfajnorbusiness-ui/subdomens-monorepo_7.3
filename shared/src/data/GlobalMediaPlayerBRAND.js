/**
 * 🛠️ HELPER: Bezpečný vyťahovač stôp a aliasovač z zbernice
 */
export const getMediaData = (mediaId) => {
  const rawId = String(mediaId || "").trim();
  
  // 1. Priama zhoda s kľúčom (napr. "SRV_01" alebo "MANIFESTO_GENESIS")
  if (GLOBAL_MEDIA_REGISTER[rawId]) {
    return GLOBAL_MEDIA_REGISTER[rawId];
  }

  // 2. Normalizácia aliasov pre S01..S18 ➔ SRV_01..SRV_18
  if (rawId.startsWith("S") && !rawId.startsWith("SRV_")) {
    const formattedSrvId = rawId.replace(/^S/, "SRV_");
    if (GLOBAL_MEDIA_REGISTER[formattedSrvId]) {
      return GLOBAL_MEDIA_REGISTER[formattedSrvId];
    }
  }

  // NÁVRAT DO PÔVODNÉHO FUNKČNÉHO STAVU:
  // Ak uzol (SUB_00) nemá vlastné video, vráť predvolené hrajúce OS Genesis video:
  return GLOBAL_MEDIA_REGISTER.MANIFESTO_GENESIS;
};
